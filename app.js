function hashNumber(input) {
  const str = String(input);
  let hash = 0;

  for (let i = 0; i < str.length; i++) {
    hash = (hash * 31 + str.charCodeAt(i)) >>> 0;
  }

  return hash;
}

function generateNumber(selectedNumber) {
  return (hashNumber(selectedNumber) % 200) + 1;
}

document.getElementById("drawBtn").addEventListener("click", () => {
  const input = document.getElementById("numberInput").value;

  if (!input) {
    alert("请先输入一个数字");
    return;
  }

  const generatedNumber = generateNumber(input);
  const punishment = punishments[generatedNumber] || `编号 ${generatedNumber} 的惩罚题目暂未录入`;

  document.getElementById("selectedNumber").textContent = input;
  document.getElementById("generatedNumber").textContent = generatedNumber;
  document.getElementById("punishmentText").textContent = punishment;

  document.getElementById("result").classList.remove("hidden");
});